# Load local .env values without overriding environment variables provided by the OS.
local_env_file = BASE_DIR / '.env'
if local_env_file.is_file():
    for line_number, raw_line in enumerate(local_env_file.read_text(encoding='utf-8-sig').splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith('#'):
            continue
        key, separator, value = line.partition('=')
        key = key.strip()
        if not separator or not key or not key.replace('_', '').isalnum():
            raise ValueError(f'Invalid .env entry at line {line_number}.')
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
            value = value[1:-1]
        os.environ.setdefault(key, value)


