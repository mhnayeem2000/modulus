SUBJECT_CHOICES = tuple((subject, subject) for subject in CURRICULUM)


def paper_choices(subject):
    papers = CURRICULUM.get(subject)
    if papers:
        return tuple((paper, paper) for paper in papers)
    return ()


def chapter_choices(subject, paper):
    papers = CURRICULUM.get(subject)
    if papers:
        chapters = papers.get(paper)
        if chapters is None:
            return ()
        return tuple((chapter, chapter) for chapter in chapters)
    return ()
